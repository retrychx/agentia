/**
 * Agentia —— 换行分隔 JSON-RPC 的**分帧缓冲上限**（两条 MCP 桥**共用一份**）。
 *
 * 为什么要有这个文件：两个方向的桥各自攒一个字符串缓冲按 `\n` 切帧 ——
 *   ① 正向连接器 `integrations/mcp-stdio.ts` 读**子进程 stdout**；
 *   ② 反向桥 `engine/mcp-server-stdio.ts` 读**宿主 stdin**。
 * 两份都是 `buf += chunk` 然后找换行，**没有任何长度上限**（2026-09-28 外部深评 S6）：
 * 对端只要一直吐不带换行的字节（坏 server / 坏宿主 / 一条 5GB 的「一行」），缓冲区就无界
 * 增长 ⇒ 先 OOM 再谈协议。这不是「罕见输入」：stdout 里混日志的 MCP server 本来就常见
 * （连接器那条的注释已认下这点），而**一个不换行的日志行**就是这形态。
 *
 * 为什么两份共用一份常量而不是各写一个：这正是本仓反复吃过的「同一契约两份实现」的坑
 * （见 `docs/guards.md`）—— 两侧上限漂了不会有任何症状，直到某天一侧先 OOM。
 * 放 `core` 是因为 `integrations` 与 `engine` 都只许依赖 `core`（分层守卫），
 * 谁也不能把常量挂在对方身上。
 *
 * ⚠️ 单位是 **UTF-16 码元**（`string.length`），不是字节。为什么不按字节：两侧的缓冲都是
 * `setEncoding('utf8')` 之后的**字符串**，逐块算 `Buffer.byteLength` 要么每次重算整段
 * （O(n²)），要么另维护一个字节计数器（同一段缓冲两套长度，迟早漂）。码元长度是现成的、
 * 单调递增的，做**上限**足够 —— 而且它是**保守**的：每个码元在内存里最少占 2 字节，
 * 所以真实内存占用 ≤ 2× 这个值，不会低估到危险。
 *
 * 取值口径：**远大于任何合法报文，远小于能让进程 OOM**。MCP 的单条报文里可能装着工具结果
 * （整份文件、整段日志），给小了会把正常调用打成协议错 —— 那比 OOM 更难查（症状是「偶发
 * 失败」）。800 万码元是「一次性工具结果」的宽裕上界，同时上千个并发连接各自缓冲一份也仍
 * 在几 GB 量级之外。
 *
 * ⚠️ 这是**硬上限，不是旋钮**：它没有「0 = 不限」的读法，所以不进 `core/limits.ts` 的旋钮表
 * （那张表管的是「使用者能设的旋钮，0 是什么意思」）。要改它只能改代码 + 两侧用例。
 */
export const MAX_FRAME_CHARS = 8 * 1024 * 1024;

/**
 * 上限的人类可读说法（两条桥的报错文案共用 —— 免得一处写「8 MiB」一处写「8388608」）。
 * 数值与 `MAX_FRAME_CHARS` 同源，改上限不会让文案漂。
 */
export function frameLimitText(): string {
  return `${MAX_FRAME_CHARS} 码元（约 ${MAX_FRAME_CHARS / (1024 * 1024)} MiB）`;
}
